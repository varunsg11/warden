"""Aggregate results/agentdojo/raw/*.json into results/agentdojo/README.md.

Totals are pooled, not averaged over suites: utility over all user tasks, attack
success (ASR) and utility-under-attack over all (user task, injection task) pairs.
With repeated runs, each cell is mean +/- sample std over reps. Subset (smoke)
runs are skipped.

  python experiments/agentdojo/summarize.py
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean, stdev

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results" / "agentdojo"
SUITES = ("workspace", "travel", "banking", "slack")
CONFIG_ORDER = ("none", "suite", "task", "oracle", "task+prov")
CONFIG_LABEL = {
    "none": "no defense",
    "suite": "Warden, suite-wide policy",
    "task": "**Warden, per-task policy**",
    "oracle": "Warden, oracle policy (upper bound)",
    "task+prov": "**Warden, per-task + provenance**",
}


def _pooled(run: dict, names: list[str]) -> dict[str, float]:
    """Pool a run's results over the suites in `names` (so configs run on
    different suite sets are compared only where they overlap)."""
    suites = [run["suites"][s] for s in names]
    tasks = sum(s["n_user_tasks"] for s in suites)
    pairs = sum(s["n_pairs"] for s in suites)
    return {
        "utility": sum(s["utility"] * s["n_user_tasks"] for s in suites) / tasks,
        "utility_under_attack": sum(s["utility_under_attack"] * s["n_pairs"] for s in suites)
        / pairs,
        "asr": sum(s["asr"] * s["n_pairs"] for s in suites) / pairs,
        **{f"asr_{s}": run["suites"][s]["asr"] for s in names},
    }


def _cell(values: list[float]) -> str:
    if not values:
        return "—"
    if len(values) == 1:
        return f"{values[0]:.1%}"
    return f"{mean(values):.1%} ± {stdev(values):.1%}"


def main() -> None:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for path in sorted((RESULTS / "raw").glob("*.json")):
        run = json.loads(path.read_text(encoding="utf-8"))
        meta = run["meta"]
        if meta.get("subset"):
            continue
        groups[(meta["model"], meta["attack"], meta["on_deny"], meta["config"])].append(run)

    lines = [
        "# Warden on AgentDojo",
        "",
        "Generated by `experiments/agentdojo/summarize.py` from `raw/*.json` — do not edit by hand.",
        "Benchmark: AgentDojo v1.2.2. Each table pools only the suites every one of its",
        "configurations ran (named in the heading when not all four); the scripted agent",
        "also excludes injection tasks it can't perform -- listed below its tables.",
        "**ASR** = targeted attack success rate (lower is better). **Utility** = user tasks",
        "completed with no attack; **under attack** = completed while being attacked.",
        "",
    ]
    by_model: dict[tuple, list[tuple]] = defaultdict(list)
    for key in groups:
        by_model[key[:3]].append(key)

    # Real models first (the headline), then the scripted worst case; within each,
    # the default quarantine mode before the error-mode ablation.
    def order(key: tuple) -> tuple:
        model, attack, on_deny = key
        return (model == "scripted", on_deny != "quarantine", model, attack)

    for model_key in sorted(by_model, key=order):
        model, attack, on_deny = model_key
        title = "scripted always-fooled agent (worst case)" if model == "scripted" else model
        keys = sorted(by_model[model_key], key=lambda k: CONFIG_ORDER.index(k[3]))
        runs_here = [r for k in keys for r in groups[k]]
        common = [s for s in SUITES if all(s in r["suites"] for r in runs_here)]
        scope = "" if common == list(SUITES) else f" — suites: {', '.join(common)}"
        lines += [
            f"## {title} — attack `{attack}`, on deny: `{on_deny}`{scope}",
            "",
            "| Configuration | Utility | Utility under attack | **ASR** "
            "| ASR workspace | ASR travel | ASR banking | ASR slack | runs |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for key in keys:
            pooled = [_pooled(r, common) for r in groups[key]]
            row = [CONFIG_LABEL.get(key[3], key[3])]
            for metric in ("utility", "utility_under_attack", "asr", *[f"asr_{s}" for s in SUITES]):
                row.append(_cell([p[metric] for p in pooled if metric in p]))
            row.append(str(len(pooled)))
            lines.append("| " + " | ".join(row) + " |")
        # Configs that also covered other suites: report their full-coverage totals too.
        for key in keys:
            for r in groups[key]:
                if set(r["suites"]) - set(common):
                    names = [s for s in SUITES if s in r["suites"]]
                    full = _pooled(r, names)
                    lines.append(
                        f"\n{CONFIG_LABEL.get(key[3], key[3])} on all of {', '.join(names)}: "
                        f"utility {full['utility']:.1%}, utility under attack "
                        f"{full['utility_under_attack']:.1%}, ASR {full['asr']:.1%}."
                    )

        denials: Counter[str] = Counter()
        for key in keys:
            for run in groups[key]:
                for s in run["suites"].values():
                    denials.update(s["denials_attacked"])
        excluded = {
            name: s.get("excluded_injection_tasks", [])
            for key in keys
            for name, s in groups[key][0]["suites"].items()
            if s.get("excluded_injection_tasks")
        }
        if excluded:
            lines += [
                "",
                "Excluded injection tasks (no tool-call ground truth for the scripted agent):",
                "",
            ]
            lines += [f"- {name}: {', '.join(ids)}" for name, ids in sorted(excluded.items())]
        if denials:
            lines += [
                "",
                "Denials under attack, by the check that failed (all Warden configs):",
                "",
            ]
            lines += [f"- `{name}`: {count}" for name, count in denials.most_common()]
        lines.append("")

    out = RESULTS / "README.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
